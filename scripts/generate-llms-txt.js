'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_FILE = path.join(ROOT, 'llms.txt');
const CONTRACT_FILE = path.join(ROOT, 'components', 'mcp', 'contracts.json');

function readContracts() {
  if (!fs.existsSync(CONTRACT_FILE)) {
    return [];
  }

  try {
    const raw = fs.readFileSync(CONTRACT_FILE, 'utf8');
    const parsed = JSON.parse(raw);
    const items = Array.isArray(parsed.components) ? parsed.components : [];

    return items
      .map((item) => ({
        name: item.component || item.name || 'unknown',
        selector: item.selector || 'unknown',
      }))
      .filter((item) => item.name !== 'unknown' || item.selector !== 'unknown');
  } catch (error) {
    return [];
  }
}

function buildContent() {
  const contracts = readContracts();
  const componentLines = contracts.length
    ? contracts.map((entry) => `- ${entry.name}: ${entry.selector}`).join('\n')
    : '- contracts unavailable (run components MCP export first)';

  const lines = [
    '# Design System Blueprint - LLM Context',
    '',
    'This file is generated in CI and is intended as a low-cost bootstrap context for coding assistants.',
    '',
    '## Repository Scope',
    '- Monorepo with Angular component library, design tokens, and MCP helpers.',
    '- Source of truth for agent policy: AGENTS.md',
    '',
    '## Decision Hierarchy (must follow)',
    '1. User request in the current task.',
    '2. AGENTS.md in repository root.',
    '3. design-tokens/token-mcp-contract.md.',
    '4. tokens-mcp implementation and tests.',
    '5. components/mcp/contracts.json and components/src/storybook/mcp.ts.',
    '6. components source and stories.',
    '',
    '## Token Policy',
    '- Return only tier 2 semantic aliases for final token recommendations.',
    '- Never return tier 1 or tier 3 as final answer.',
    '- Tier 3 is evidence only.',
    '- Value-based lookup is forbidden (hex/rgb/px-driven questions).',
    '- If no coverage exists, return no-coverage and do not guess.',
    '',
    '## Available Component Contracts',
    componentLines,
    '',
    '## Enforcement',
    '- Raw value guard script: components/scripts/lint-raw-values.js.',
    '- Baseline mode keeps selected categories as warnings.',
    '- Strict mode promotes selected categories to errors.',
    '',
    '## Primary Entry Points',
    '- Token resolver: tokens-mcp/src/token-engine.js.',
    '- Token MCP server: tokens-mcp/src/server.js.',
    '- Storybook MCP metadata: components/src/storybook/mcp.ts.',
    '- Generated contracts: components/mcp/contracts.json.',
    '',
    '## Maintenance',
    '- Generated by scripts/generate-llms-txt.js.',
    '- Regenerate after contract or policy updates.',
    '',
  ];

  return lines.join('\n');
}

function main() {
  const content = buildContent();
  fs.writeFileSync(OUT_FILE, content, 'utf8');
  console.log(`Generated ${path.relative(ROOT, OUT_FILE)}.`);
}

main();
